#!/usr/bin/env python
"""Generate ``docs/api/endpoints.md`` from ``schema.yml``.

The output is deterministic: the same schema always produces the same file, so a
reviewer can regenerate it and see whether the API surface changed.

Usage (from the repository root)::

    python manage.py spectacular --file schema.yml
    python scripts/generate_api_reference.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "schema.yml"
OUTPUT_PATH = ROOT / "docs" / "api" / "endpoints.md"

HTTP_METHODS = ("get", "post", "put", "patch", "delete")

TAG_ORDER = [
    "auth",
    "listings",
    "stores",
    "categories",
    "commerce",
    "quotes",
    "financials",
    "notifications",
    "messages",
    "inquiries",
    "reviews",
    "admin-panel",
    "analytics",
    "compliance",
    "support",
    "search",
    "careers",
    "other",
]

TAG_TITLES = {
    "auth": "Authentication, profile, and onboarding",
    "listings": "Listings and saved items",
    "stores": "Stores",
    "categories": "Categories",
    "commerce": "Cart, checkout, payments, orders, rentals, and disputes",
    "quotes": "Quote requests",
    "financials": "Wallets, earnings, bank accounts, and payouts",
    "notifications": "Notifications and channel preferences",
    "messages": "Conversations and messages",
    "inquiries": "Listing inquiries",
    "reviews": "Listing and store reviews",
    "admin-panel": "Staff dashboard",
    "analytics": "Analytics and exports",
    "compliance": "Compliance documents",
    "support": "Support tickets",
    "search": "Global search",
    "careers": "Public careers",
    "other": "Other endpoints",
}


def security_label(operation: dict) -> str:
    security = operation.get("security")
    if not security:
        return "Public"
    schemes = sorted({scheme for entry in security for scheme in entry})
    labels = []
    for scheme in schemes:
        if scheme.lower().startswith("jwt"):
            labels.append("Bearer JWT")
        else:
            labels.append(scheme)
    return ", ".join(labels) or "Public"


def request_label(operation: dict) -> str:
    body = operation.get("requestBody") or {}
    for media in (body.get("content") or {}).values():
        schema = media.get("schema") or {}
        ref = schema.get("$ref")
        if ref:
            return f"`{ref.rsplit('/', 1)[-1]}`"
        if schema.get("type"):
            return schema["type"]
    return "—"


def codes(operation: dict, prefix: str) -> str:
    values = [
        code
        for code in (operation.get("responses") or {})
        if code.startswith(prefix)
    ]
    return ", ".join(sorted(values)) or "—"


def error_codes(operation: dict) -> str:
    values = [
        code
        for code in (operation.get("responses") or {})
        if code.startswith("4") or code.startswith("5")
    ]
    return ", ".join(sorted(values)) or "—"


def summary(operation: dict) -> str:
    text = operation.get("summary") or operation.get("description") or ""
    text = " ".join(str(text).split())
    if len(text) > 120:
        text = text[:117].rstrip() + "..."
    return text.replace("|", "\\|") or "—"


def main() -> int:
    if not SCHEMA_PATH.exists():
        print(f"schema not found: {SCHEMA_PATH}", file=sys.stderr)
        return 1

    schema = yaml.safe_load(SCHEMA_PATH.read_text(encoding="utf8"))
    paths = schema.get("paths") or {}

    grouped: dict[str, list[tuple[str, str, dict]]] = {}
    operation_count = 0
    for path, methods in paths.items():
        for method, operation in methods.items():
            if method not in HTTP_METHODS:
                continue
            operation_count += 1
            tags = operation.get("tags") or ["other"]
            tag = tags[0] if tags[0] in TAG_TITLES else "other"
            grouped.setdefault(tag, []).append((path, method, operation))

    ordered_tags = [tag for tag in TAG_ORDER if tag in grouped]
    ordered_tags += sorted(tag for tag in grouped if tag not in ordered_tags)

    lines: list[str] = []
    lines.append("# API endpoint reference")
    lines.append("")
    lines.append(
        "> Generated from `schema.yml` by `scripts/generate_api_reference.py`. "
        "Do not edit this file by hand."
    )
    lines.append(">")
    lines.append(
        "> Regenerate with `python manage.py spectacular --file schema.yml` "
        "then `python scripts/generate_api_reference.py`."
    )
    lines.append("")
    lines.append(f"**{len(paths)} paths · {operation_count} operations.**")
    lines.append("")
    lines.append(
        "`Auth` is `Public` when the operation needs no token; otherwise it names the "
        "required scheme (`Bearer JWT`). A token sent to a public read is only used where "
        "it changes the result (for example, a listing detail or search history)."
    )
    lines.append("")
    lines.append("## Contents")
    lines.append("")
    for tag in ordered_tags:
        lines.append(
            f"- [{TAG_TITLES[tag]}](#{tag}) "
            f"({len(grouped[tag])} operations)"
        )
    lines.append("")

    for tag in ordered_tags:
        lines.append(f"## {tag}")
        lines.append("")
        lines.append(f"*{TAG_TITLES[tag]}.*")
        lines.append("")
        lines.append("| Method | Path | Operation ID | Summary | Auth | Request | Success | Errors |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for path, method, operation in sorted(
            grouped[tag], key=lambda item: (item[0], HTTP_METHODS.index(item[1]))
        ):
            lines.append(
                "| {method} | `{path}` | `{op_id}` | {summary} | {auth} | "
                "{request} | {success} | {errors} |".format(
                    method=method.upper(),
                    path=path,
                    op_id=operation.get("operationId", "—"),
                    summary=summary(operation),
                    auth=security_label(operation),
                    request=request_label(operation),
                    success=codes(operation, "2"),
                    errors=error_codes(operation),
                )
            )
        lines.append("")

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines).rstrip() + "\n", encoding="utf8")
    print(f"wrote {OUTPUT_PATH.relative_to(ROOT)} ({operation_count} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
